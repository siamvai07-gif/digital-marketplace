/**
 * Generates SQL that seeds the live `nexus` schema with the exact demo catalogue
 * taken from the Admin Panel, so the database and the panel cannot drift.
 *
 * Output: scripts/seed-supabase.generated.sql
 * Apply with:  supersabase execute_query <file>   (or `psql -f`)
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const adminHtml = fs.readFileSync(path.join(root, 'admin/index.html'), 'utf8');

function extractObject(name) {
  const start = adminHtml.indexOf('const ' + name + ' = {');
  if (start < 0) throw new Error('could not find ' + name);
  const open = adminHtml.indexOf('{', start);
  let depth = 0;
  for (let j = open; j < adminHtml.length; j++) {
    const c = adminHtml[j];
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return adminHtml.slice(open, j + 1); }
  }
  throw new Error('unbalanced braces in ' + name);
}

const J = v => JSON.stringify(v).replace(/'/g, "''") + '::jsonb';

const demoProducts = Function('return ' + extractObject('demoProducts'))();
const defaultRates = Function('return ' + extractObject('defaultRates'))();
const demoReviews = Function('return ' + extractObject('demoReviews'))();
const demoCoupons = Function('return ' + extractObject('demoCoupons'))();

const out = [];
out.push('-- Generated by scripts/seed-supabase.mjs — do not edit by hand.');
out.push('begin;');

const prodRows = Object.entries(demoProducts)
  .map(([id, p]) => `  ('${id}', ${J({ ...p, id })})`)
  .join(',\n');
out.push(`insert into nexus.products (id, data) values\n${prodRows}\non conflict (id) do update set data = excluded.data, updated_at = now();`);

const revRows = Object.entries(demoReviews)
  .map(([id, r]) => `  ('${id}', ${J({ ...r, id })})`)
  .join(',\n');
out.push(`insert into nexus.reviews (id, data) values\n${revRows}\non conflict (id) do update set data = excluded.data, updated_at = now();`);

const settings = {
  dollarRates: defaultRates,
  coupons: demoCoupons,
  brand: {
    name: 'Nexus Digital',
    tagline: "Bangladesh's Premium Digital Marketplace",
    supportEmail: 'support@nexusdigital.app',
    supportWhatsapp: '+8801700000000',
    currency: 'BDT',
    coinRate: 1,
  },
  site: {
    maintenance: false,
    guestLoginEnabled: true,
    signupEnabled: true,
    minTopup: 50,
    maxTopup: 50000,
  },
};

const setRows = Object.entries(settings)
  .map(([id, v]) => `  ('${id}', ${J(v)})`)
  .join(',\n');
out.push(`insert into nexus.settings (id, data) values\n${setRows}\non conflict (id) do update set data = excluded.data, updated_at = now();`);

out.push('commit;');
out.push(`select 'products' as tbl, count(*)::text as rows from nexus.products
union all select 'reviews', count(*)::text from nexus.reviews
union all select 'settings', count(*)::text from nexus.settings;`);

const file = path.join(root, 'scripts/seed-supabase.generated.sql');
fs.writeFileSync(file, out.join('\n\n') + '\n');
console.log('wrote', file, fs.statSync(file).size, 'bytes');
console.log(`products=${Object.keys(demoProducts).length} reviews=${Object.keys(demoReviews).length} settings=${Object.keys(settings).length}`);
